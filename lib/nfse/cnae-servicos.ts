export interface CnaeEmpresa {
  /** Só dígitos: 7 posições. */
  codigo: string;
  descricao: string;
  principal: boolean;
}

export interface SugestaoCnae extends CnaeEmpresa {
  servicos: string[];
}

/** 6920601 → 6920-6/01 */
export const formatarCnae = (c: string) => c.replace(/^(\d{4})(\d)(\d{2})$/, '$1-$2/$3');

export function servicosDoCnae(codigo: string): string[] {
  const digitos = codigo.replace(/\D/g, '');
  for (let tamanho = digitos.length; tamanho > 0; tamanho--) {
    const servicos = SERVICOS_POR_CNAE[digitos.slice(0, tamanho)];
    if (servicos) return servicos;
  }
  return [];
}

/** O principal vem primeiro, e um código sugerido por um CNAE não se repete nos seguintes. */
export function sugerirServicos(cnaes: CnaeEmpresa[]): SugestaoCnae[] {
  const vistos = new Set<string>();
  return [...cnaes]
    .sort((a, b) => Number(b.principal) - Number(a.principal))
    .map(cnae => {
      const servicos = servicosDoCnae(cnae.codigo).filter(s => !vistos.has(s));
      servicos.forEach(s => vistos.add(s));
      return { ...cnae, servicos };
    });
}
